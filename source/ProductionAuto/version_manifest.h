// version_manifest.h — 版本适配清单（所有游戏版本相关数据的唯一来源）
//
// ============================================================
// 使用说明（AI 版本适配指南）
// ============================================================
//
// 当游戏更新到新版本时，按以下步骤更新本文件：
//
// 1. 获取新 exe 信息：
//    - 文件大小（字节）
//    - SHA-256 哈希
//    - 游戏版本号和 build 号
//
// 2. 运行 aob_scanner.ps1 自动扫描新 RVA：
//    powershell -File aob_scanner.ps1 -ExePath "village.exe"
//    脚本会用每个函数的 AOB 签名在 .text 段中搜索，
//    输出所有匹配的 RVA 地址。
//
// 3. 将扫描结果填入下方对应的 VERSION_MANIFEST 块：
//    - 更新 EXE_SIZE 和 EXE_SHA256
//    - 更新 GAME_VERSION 和 BUILD_NUMBER
//    - 更新所有 RVA 值
//    - 如果某个函数签名也变了，更新对应的 SIGNATURE 数组
//
// 4. 更新 RTTI 地址（脚本无法自动扫描的）：
//    - RTTI 地址可通过 IDA/Ghidra 或 PE 分析工具获取
//    - 主要是 vtable/COL/type_descriptor 地址
//    - 参考 adaptation_guide.md 中的详细说明
//
// 5. 重新编译：
//    MSBuild ProductionAuto.vcxproj /p:Configuration=Release /p:Platform=x64
//
// 6. 测试：部署到 mods\ProductionAuto_v1.0.0\，启动游戏，
//    检查 qol_productionauto.log 中所有签名校验是否 OK。
//
// ============================================================
// 文件结构：
//   PART 1: exe 指纹
//   PART 2: 通用 RVA（game_root, spatial_test）
//   PART 3: GameClock hook RVA + 签名
//   PART 4: NearbyChestSort RVA + 签名
//   PART 5: ProductionAutomation RVA + 签名
//   PART 6: RTTI 地址（vtable/COL/type_descriptor）
// ============================================================

